import json
from datetime import datetime, timedelta

def generate_ics_from_roadmap(roadmap_plan_json: str, title: str) -> str:
    """Generate an iCalendar (.ics) string from roadmap JSON."""
    try:
        plan = json.loads(roadmap_plan_json)
    except:
        return ""
        
    days = plan.get("days", plan) if isinstance(plan, dict) else plan
    if isinstance(days, dict):
        days = days.get("days", [])
        
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//Brihaspati AI Study Hub//EN",
        "CALSCALE:GREGORIAN"
    ]
    
    for day in days:
        date_str = day.get("date")
        if not date_str: continue
        
        # Approximate a start time at 17:00 (5 PM)
        try:
            start_date = datetime.fromisoformat(date_str).replace(hour=17, minute=0, second=0)
        except ValueError:
            continue
            
        for task in day.get("tasks", []):
            task_name = task.get("topic", task.get("name", "Study Session"))
            duration_min = int(task.get("duration_minutes", 60))
            end_date = start_date + timedelta(minutes=duration_min)
            
            dtstamp = datetime.now().strftime("%Y%m%dT%H%M%SZ")
            dtstart = start_date.strftime("%Y%m%dT%H%M%S")
            dtend = end_date.strftime("%Y%m%dT%H%M%S")
            
            lines.extend([
                "BEGIN:VEVENT",
                f"SUMMARY:{title} - {task_name}",
                f"DTSTAMP:{dtstamp}",
                f"DTSTART;TZID=UTC:{dtstart}",
                f"DTEND;TZID=UTC:{dtend}",
                f"DESCRIPTION:Generated by Brihaspati AI Study Coach. {task.get('objective', '')}",
                "END:VEVENT"
            ])
            start_date = end_date # next task starts after this one
            
    lines.append("END:VCALENDAR")
    return "\n".join(lines)
